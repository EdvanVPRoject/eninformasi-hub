import esbuild from 'esbuild';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = path.resolve(__dirname, '..');

async function main() {
  console.log('⚡ Building lightweight article summaries...');
  const entryPath = path.join(ROOT_DIR, 'lib', 'articles.ts');
  const tempPath = path.join(ROOT_DIR, 'scripts', '_temp_articles_bundle.mjs');
  const outputPath = path.join(ROOT_DIR, 'lib', 'data', 'article-summaries.ts');

  // Bundle lib/articles.ts with esbuild
  await esbuild.build({
    entryPoints: [entryPath],
    bundle: true,
    format: 'esm',
    outfile: tempPath,
    target: 'node20',
    platform: 'node',
  });

  // Import the generated bundle
  const tempUrl = `file:///${tempPath.replace(/\\/g, '/')}`;
  const { allArticles } = await import(tempUrl);

  // Clean up temp file
  if (fs.existsSync(tempPath)) {
    fs.unlinkSync(tempPath);
  }

  // Strip content, steps, toc to make lightweight summaries
  const summaries = allArticles.map((a) => ({
    slug: a.slug,
    title: a.title,
    description: a.description,
    postType: a.postType,
    category: a.category,
    categoryLabel: a.categoryLabel,
    difficulty: a.difficulty,
    pubDate: a.pubDate,
    updatedDate: a.updatedDate,
    readingTime: a.readingTime,
    author: a.author,
    tags: a.tags || [],
    en: a.en
      ? {
          title: a.en.title,
          description: a.en.description,
        }
      : undefined,
  }));

  const fileContent = `// Auto-generated by scripts/build-summaries.mjs - DO NOT EDIT MANUALLY
export interface ArticleSummary {
  slug: string;
  title: string;
  description: string;
  postType: 'tutorial' | 'artikel';
  category: string;
  categoryLabel: string;
  difficulty?: string;
  pubDate: string;
  updatedDate: string;
  readingTime: string;
  author: string;
  tags: string[];
  en?: {
    title?: string;
    description?: string;
  };
}

export const articleSummaries: ArticleSummary[] = ${JSON.stringify(summaries, null, 2)};

export const totalArticleCount = articleSummaries.length;
export const tutorialArticleCount = articleSummaries.filter((a) => a.postType === 'tutorial').length;
export const artikelArticleCount = articleSummaries.filter((a) => a.postType === 'artikel').length;

export function getCategoriesWithCount(postType?: 'tutorial' | 'artikel'): { id: string; label: string; count: number }[] {
  const baseList = postType ? articleSummaries.filter((a) => a.postType === postType) : articleSummaries;

  const categories = [
    { id: 'all', label: 'Semua Topik' },
    { id: 'gaming-esports', label: 'Gaming & Esports' },
    { id: 'tech-gadgets', label: 'Teknologi & Hardware' },
    { id: 'ai-agents', label: 'AI Agents & Otomasi' },
    { id: 'llm-models', label: 'LLM & Model Cerdas' },
    { id: 'tools-automation', label: 'Dev Tools & Workflow' },
    { id: 'prompting', label: 'Prompt Engineering' },
    { id: 'hardware-setup', label: 'Rig Local AI & Komputasi' },
  ];

  return categories.map((cat) => {
    const count =
      cat.id === 'all'
        ? baseList.length
        : baseList.filter((a) => a.category === cat.id).length;
    return { ...cat, count };
  });
}

export function searchArticleSummaries(query: string, postType?: 'tutorial' | 'artikel'): ArticleSummary[] {
  let list = articleSummaries;
  if (postType) {
    list = list.filter((a) => a.postType === postType);
  }
  if (!query.trim()) return list;
  const q = query.toLowerCase();
  return list.filter(
    (a) =>
      a.title.toLowerCase().includes(q) ||
      a.description.toLowerCase().includes(q) ||
      (a.en?.title && a.en.title.toLowerCase().includes(q)) ||
      (a.en?.description && a.en.description.toLowerCase().includes(q)) ||
      a.categoryLabel.toLowerCase().includes(q) ||
      a.tags.some((t) => t.toLowerCase().includes(q))
  );
}
`;

  fs.writeFileSync(outputPath, fileContent, 'utf8');
  console.log(`✅ [Summary Generator] Successfully generated ${summaries.length} lightweight article summaries in lib/data/article-summaries.ts!`);
}

main().catch((err) => {
  console.error('❌ Failed to generate summaries:', err);
  process.exit(1);
});
