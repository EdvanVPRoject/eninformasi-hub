export function getTranslation(lang: Language, key: keyof typeof translations['id'], fallback?: string): string {
  const dict = translations[lang] || translations.id;
  return dict[key] || fallback || key;
}

export function getCategoryLabel(category: string, lang: Language): string {
  const map: Record<string, { id: string; en: string }> = {
    'all': { id: 'Semua Kategori', en: 'All Categories' },
    'ai-agents': { id: 'AI Agents & Otomasi', en: 'AI Agents & Automation' },
    'llm-models': { id: 'LLM & Model Open-Source', en: 'LLMs & Open-Source Models' },
    'tools-automation': { id: 'Workflow & Tooling', en: 'Workflows & Tooling' },
    'prompting': { id: 'Prompt Engineering & Bisnis', en: 'Prompt Engineering & Business' },
    'hardware-setup': { id: 'Hardware & Local AI', en: 'Hardware & Local AI' },
    'gaming-esports': { id: 'Gaming & Esports', en: 'Gaming & Esports' },
    'upcoming-booming': { id: 'Tren Booming & Rilis', en: 'Upcoming Releases & Trends' },
    'tech-gadgets': { id: 'Teknologi & Hardware', en: 'Technology & Hardware' }
  };

  if (map[category]) {
    return lang === 'en' ? map[category].en : map[category].id;
  }
  return category;
}

export function getDifficultyLabel(diff?: string, lang: Language = 'id'): string {
  if (!diff) return lang === 'en' ? 'General' : 'Umum';
  const lower = diff.toLowerCase();
  if (lower === 'pemula' || lower === 'mudah') return lang === 'en' ? 'Beginner' : 'Pemula';
  if (lower === 'menengah') return lang === 'en' ? 'Intermediate' : 'Menengah';
  if (lower === 'mahir' || lower === 'lanjutan') return lang === 'en' ? 'Advanced' : 'Mahir';
  return diff;
}
